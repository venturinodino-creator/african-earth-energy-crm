/* One glyph per sector GROUP rather than per sector — 30 distinct icons
   would be noise, and the group is what the eye actually sorts by. */
const GROUP_ICON = {
  'heavy-industry': ICONS.bolt,
  'manufacturing': ICONS.factory,
  'commercial': ICONS.building,
  'digital': ICONS.grid,
  'logistics': ICONS.truck,
  'utilities-public': ICONS.pin,
  'primary': ICONS.leaf,
  'emerging': ICONS.sun,
};

function icon(name, size) { return svg(ICONS[name] || ICONS.building, size); }

/* Takes a sector id and resolves through the taxonomy to its group. */
function sectorIcon(sectorId, size) {
  const group = (typeof SECTOR_BY_ID !== 'undefined' && SECTOR_BY_ID[sectorId])
    ? SECTOR_BY_ID[sectorId].group : null;
  return svg(GROUP_ICON[group] || ICONS.building, size);
}
